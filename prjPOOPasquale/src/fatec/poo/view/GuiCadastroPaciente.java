    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
        String cpfNumeros = ftxCPF.getText().replaceAll("[^0-9]", "");
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        

        if ( cpfNumeros == null || !paciente.validarCPF(cpfNumeros)) {
            JOptionPane.showMessageDialog(this, "CPF inválido!", "Erro de Validação", JOptionPane.ERROR_MESSAGE);

            ftxCPF.setEnabled(true);
            ftxCPF.requestFocus();

            return;
        }

        //verificar aqui
        paciente = new Paciente(cpfNumeros, txtNome.getText(), LocalDate.parse(ftxDataNascimento.getText(), formatter));
        paciente.setEndereco(txtEndereco.getText());
        paciente.setTelefone(txtTelefone.getText());
        paciente.setAltura(Double.parseDouble(txtAltura.getText().replace(",",".")));
        paciente.setPeso(Double.parseDouble(txtPeso.getText().replace(",",".")));

        daoPaciente.inserir(paciente);
        JOptionPane.showMessageDialog(this, "Paciente inserido com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);

        ftxCPF.setText("");
        txtNome.setText("");
        txtEndereco.setText("");
        txtTelefone.setText("");
        ftxDataNascimento.setText("");
        txtAltura.setText("");
        txtPeso.setText("");

        ftxCPF.setEnabled(true);
        txtNome.setEnabled(false);
        txtEndereco.setEnabled(false);
        txtTelefone.setEnabled(false);
        ftxDataNascimento.setEnabled(false);
        txtAltura.setEnabled(false);
        txtPeso.setEnabled(false);

        btnConsultar.setEnabled(true);
        btnInserir.setEnabled(false);
        btnAlterar.setEnabled(false);
        btnExcluir.setEnabled(false);

        ftxCPF.requestFocus();

    }//GEN-LAST:event_btnInserirActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (JOptionPane.showConfirmDialog(null, "Confirma Alteração dos Dados do Paciente?") == 0) {
            String novoEndereco = txtEndereco.getText();
            String novoTelefone = txtTelefone.getText();
            String novaAltura = txtAltura.getText();
            String novoPeso = txtPeso.getText();

            if (novaAltura.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "A altura não pode estar vazio.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                txtAltura.requestFocus();
            } else if (novoPeso.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "O peso não pode estar vazio.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                txtPeso.requestFocus();
            }else if(novoEndereco.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "O endereço não pode estar vazio.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                txtEndereco.requestFocus();
            } else if (novoTelefone.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "O telefone não pode estar vazio.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                txtTelefone.requestFocus();
            }

            paciente.setEndereco(novoEndereco);
            paciente.setTelefone(novoTelefone);
            paciente.setAltura(Double.parseDouble(novaAltura));
            paciente.setPeso(Double.parseDouble(novoPeso));
            daoPaciente.alterar(paciente);
            JOptionPane.showMessageDialog(this, "Dados do paciente alterados com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
        }
        ftxCPF.setText("");
        txtNome.setText("");
        txtEndereco.setText("");
        txtTelefone.setText("");
        ftxDataNascimento.setText("");
        txtAltura.setText("");
        txtPeso.setText("");

        ftxCPF.setEnabled(true);
        txtNome.setEnabled(false);
        txtEndereco.setEnabled(false);
        txtTelefone.setEnabled(false);
        ftxDataNascimento.setEnabled(false);
        txtAltura.setEnabled(false);
        txtPeso.setEnabled(false);

        btnConsultar.setEnabled(true);
        btnInserir.setEnabled(false);
        btnAlterar.setEnabled(false);
        btnExcluir.setEnabled(false);

        ftxCPF.requestFocus();

        paciente = null;
    }//GEN-LAST:event_btnAlterarActionPerformed

