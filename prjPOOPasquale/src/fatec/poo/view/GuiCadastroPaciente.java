    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        String cpfFormatado = ftxCPF.getText();
        String cpfNumeros = cpfFormatado.replaceAll("[^0-9]", "");

        if (!paciente.validarCPF(cpfNumeros)) {
            JOptionPane.showMessageDialog(this, "CPF inválido!", "Erro de Validação", JOptionPane.ERROR_MESSAGE);

            ftxCPF.setEnabled(true);
            ftxCPF.requestFocus();

            return;
        }

        paciente = daoPaciente.consultar(cpfNumeros);

        if (paciente != null) {
            txtNome.setText(paciente.getNome());
            txtEndereco.setText(paciente.getEndereco());
            txtTelefone.setText(paciente.getTelefone());
            ftxDataNascimento.setText(String.valueOf(paciente.getDataNascimento()));
            txtAltura.setText(String.valueOf(paciente.getAltura()));
            txtPeso.setText(String.valueOf(paciente.getPeso()));

            ftxCPF.setEnabled(false);
            txtNome.setEnabled(false);
            txtEndereco.setEnabled(true);
            txtTelefone.setEnabled(true);
            ftxDataNascimento.setEnabled(false);
            txtAltura.setEnabled(true);
            txtPeso.setEnabled(true);

            btnConsultar.setEnabled(false);
            btnInserir.setEnabled(false);
            btnAlterar.setEnabled(true);
            btnExcluir.setEnabled(true);

            txtNome.requestFocus();
        } else {
            JOptionPane.showMessageDialog(this, "Paciente não cadastrado. Prossiga com a inserção de dados.", "Informação", JOptionPane.INFORMATION_MESSAGE);

            txtNome.setText("");
            txtEndereco.setText("");
            txtTelefone.setText("");
            ftxDataNascimento.setText("");
            txtAltura.setText("");
            txtPeso.setText("");

            ftxCPF.setEnabled(false);
            txtNome.setEnabled(true);
            txtEndereco.setEnabled(true);
            txtTelefone.setEnabled(true);
            ftxDataNascimento.setEnabled(true);
            txtAltura.setEnabled(true);
            txtPeso.setEnabled(true);

            btnConsultar.setEnabled(false);
            btnInserir.setEnabled(true);
            btnAlterar.setEnabled(false);
            btnExcluir.setEnabled(false);

            txtNome.requestFocus();
        }

    }//GEN-LAST:event_btnConsultarActionPerformed

