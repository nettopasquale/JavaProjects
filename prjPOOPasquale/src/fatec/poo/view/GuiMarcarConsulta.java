    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
        int codigo;
        String cpfPaciente = ftxCPFPaciente.getText().replaceAll("[^0-9]", "");
        String data = ftxData.getText();
        String valorText = txtValor.getText();
        Double valor;

        if (cpfPaciente == null || !paciente.validarCPF(cpfPaciente)) {
            JOptionPane.showMessageDialog(this, "CPF inválido!", "Erro de Validação", JOptionPane.ERROR_MESSAGE);

            ftxCPFPaciente.setEnabled(true);
            ftxCPFPaciente.requestFocus();

            return;
        }

        try {
            codigo = Integer.parseInt(txtCodigo.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Código inválido.", "Erro", JOptionPane.ERROR_MESSAGE);
            txtCodigo.requestFocus();
            return;
        }

        if (data.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Data não pode estar vazia.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
            ftxData.requestFocus();
            return;
        }

        try {
            valor = Double.parseDouble(txtValor.getText().replace(",", "."));
            if (valor < 0) {
                JOptionPane.showMessageDialog(this, "Valor não pode ser negativo.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                txtValor.requestFocus();
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Valor inválido para consulta.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
            txtValor.requestFocus();
            return;
        }

        consulta = new Consulta(codigo, data);
        consulta.setValor(valor);
        consulta.setMedico(medico);

        paciente.addConsultas(consulta);

        daoConsulta.inserir(consulta, cpfPaciente);
        JOptionPane.showMessageDialog(this, "Consulta inserida com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);

        txtCodigo.setText("");
        ftxCPFMedico.setText("");
        ftxCPFPaciente.setText("");
        txtNomeMedico.setText("");
        txtNomePaciente.setText("");
        ftxData.setText("");
        txtValor.setText("");

        txtCodigo.setEnabled(true);
        ftxCPFMedico.setEnabled(false);
        ftxCPFPaciente.setEnabled(false);
        ftxData.setEnabled(false);
        txtValor.setEnabled(false);
        txtNomeMedico.setEnabled(false);
        txtNomePaciente.setEnabled(false);

        btnConsultar.setEnabled(true);
        btnInserir.setEnabled(false);
        btnAlterar.setEnabled(false);
        btnExcluir.setEnabled(false);

        txtCodigo.requestFocus();

        consulta = null;
    }//GEN-LAST:event_btnInserirActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (JOptionPane.showConfirmDialog(null, "Confirma Alteração dos Dados do Hóspede?") == 0) {
            String novaData = ftxData.getText();
            String cpfPaciente = ftxCPFPaciente.getText().replaceAll("[^0-9]", "");
            Double novoValor;

            if (novaData.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "A data não pode estar vazia.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                ftxData.requestFocus();
            }

            try {
                if (txtValor.getText().trim().isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Valor não pode estar vazio.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                    txtValor.requestFocus();
                    return;
                }

                novoValor = Double.parseDouble(txtValor.getText().replace(",", "."));
                if (novoValor < 0) {
                    JOptionPane.showMessageDialog(this, "Valor não pode ser negativo.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                    txtValor.requestFocus();
                    return;
                }
                consulta.setValor(novoValor);
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Valor inválido para consulta. Use números.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
                txtValor.requestFocus();
                return;
            }

            consulta.setData(novaData);

            daoConsulta.alterar(consulta, cpfPaciente);
            JOptionPane.showMessageDialog(this, "Dados da consulta alterados com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
        }

        txtCodigo.setText("");
        ftxCPFMedico.setText("");
        ftxCPFPaciente.setText("");
        txtNomeMedico.setText("");
        txtNomePaciente.setText("");
        ftxData.setText("");
        txtValor.setText("");

        txtCodigo.setEnabled(true);
        ftxCPFMedico.setEnabled(false);
        ftxCPFPaciente.setEnabled(false);
        ftxData.setEnabled(false);
        txtValor.setEnabled(false);
        txtNomeMedico.setEnabled(false);
        txtNomePaciente.setEnabled(false);

        btnConsultar.setEnabled(true);
        btnInserir.setEnabled(false);
        btnAlterar.setEnabled(false);
        btnExcluir.setEnabled(false);

        txtCodigo.requestFocus();

        consulta = null;

    }//GEN-LAST:event_btnAlterarActionPerformed

