    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        int codigo;

        try {
            codigo = Integer.parseInt(txtCodigo.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Código da Consulta inválido. Informe um número inteiro.", "Erro de Entrada", JOptionPane.ERROR_MESSAGE);
            txtCodigo.setText("");
            txtCodigo.requestFocus();
            return;
        }

        consulta = daoConsulta.consultar(codigo);
        paciente = null;

        if (consulta != null) {

            ftxCPFMedico.setText(consulta.getMedico().getCpf());
            txtNomeMedico.setText(consulta.getMedico().getNome());

            String cpfPaciente = consulta.getCpfPaciente();
            paciente = daoPaciente.consultar(cpfPaciente);

            
            ftxCPFPaciente.setText(paciente.getCpf());
            txtNomePaciente.setText(paciente.getNome());

            ftxData.setText(consulta.getData());
            txtValor.setText(String.valueOf(consulta.getValor()));

            txtCodigo.setEnabled(false);
            ftxCPFMedico.setEnabled(false);
            ftxCPFPaciente.setEnabled(false);
            ftxData.setEnabled(true);
            txtValor.setEnabled(true);
            txtNomeMedico.setEnabled(false);
            txtNomePaciente.setEnabled(false);

            btnConsultar.setEnabled(false);
            btnInserir.setEnabled(false);
            btnAlterar.setEnabled(true);
            btnExcluir.setEnabled(true);

            ftxCPFMedico.requestFocus();

        } else {
            JOptionPane.showMessageDialog(this, "Consulta não cadastrada. Prossiga com a inserção de dados.", "Informação", JOptionPane.INFORMATION_MESSAGE);

            ftxCPFMedico.setText("");
            ftxCPFPaciente.setText("");
            txtNomeMedico.setText("");
            txtNomePaciente.setText("");
            ftxData.setText("");
            txtValor.setText("");

            txtCodigo.setEnabled(false);
            ftxCPFMedico.setEnabled(true);
            ftxCPFPaciente.setEnabled(false);
            ftxData.setEnabled(true);
            txtValor.setEnabled(true);
            txtNomeMedico.setEnabled(false);
            txtNomePaciente.setEnabled(false);

            btnConsultar.setEnabled(false);
            btnBuscarCPFMedico.setEnabled(true);
            btnInserir.setEnabled(true);
            btnAlterar.setEnabled(false);
            btnExcluir.setEnabled(false);

            ftxCPFMedico.requestFocus();

        }

    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnBuscarCPFMedicoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarCPFMedicoActionPerformed
        String cpfFormatado = ftxCPFMedico.getText();
        String cpfNumeros = cpfFormatado.replaceAll("[^0-9]", "");

        if (!medico.validarCPF(cpfNumeros)) {
            JOptionPane.showMessageDialog(this, "CPF inválido!", "Erro de Validação", JOptionPane.ERROR_MESSAGE);

            ftxCPFMedico.setEnabled(true);
            ftxCPFMedico.requestFocus();

            return;
        }

        medico = daoMedico.consultar(cpfNumeros);

        if (medico == null) {
            JOptionPane.showMessageDialog(null, "Médico não cadastrado.", "Aviso", JOptionPane.WARNING_MESSAGE);
            ftxCPFMedico.setText("");
            ftxCPFMedico.requestFocus();
        } else {
            txtNomeMedico.setText(medico.getNome());

            ftxCPFMedico.setEnabled(false);
            btnBuscarCPFMedico.setEnabled(false);

            ftxCPFPaciente.setEnabled(true);
            btnBuscarCPFPaciente.setEnabled(true);
            ftxCPFPaciente.requestFocus();
        }


    }//GEN-LAST:event_btnBuscarCPFMedicoActionPerformed

